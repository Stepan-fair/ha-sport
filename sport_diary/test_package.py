"""Verify the installation ZIP, image inputs and self-contained offline interface."""
from html.parser import HTMLParser
import os
from pathlib import Path
import subprocess
import sys
from tempfile import TemporaryDirectory
import unittest
from unittest.mock import patch
from zipfile import ZipFile

import package
import test_sport


class PageAssets(HTMLParser):
    def __init__(self):
        super().__init__()
        self.assets = []

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == "script" and "src" in attrs:
            self.assets.append(attrs["src"])
        if tag == "link" and attrs.get("rel") == "stylesheet":
            self.assets.append(attrs["href"])


class ReleasePackage(unittest.TestCase):
    def test_installation_and_offline_preview(self):
        with TemporaryDirectory() as temporary:
            folder = Path(temporary)
            package.build(folder)
            preview = (folder / "Sport-preview.html").read_text(encoding="utf8")
            page = PageAssets()
            page.feed(preview)
            self.assertEqual(page.assets, [])
            self.assertIn(package.LOCAL_REQUEST, preview)
            with ZipFile(folder / "Sport-HA.zip") as archive:
                self.assertIsNone(archive.testzip())
                self.assertEqual(archive.namelist(), ["sport/" + name for name in package.INSTALL_FILES])
                archive.extractall(folder)
            app = folder / "sport"
            dockerfile = (app / "Dockerfile").read_text(encoding="utf8").replace("\\\n", " ")
            image_sources = set()
            for line in dockerfile.splitlines():
                if line.startswith("COPY "):
                    for source in line.split()[1:-1]:
                        self.assertTrue((app / source).is_file(), source)
                        image_sources.add(source)
            self.assertIn("health_sensors.py", image_sources)
            # The two virtual JS endpoints are generated by the HTTP handler from packaged JSON.
            virtual = {"catalog.js": "catalog.json", "food-words.js": "food-words.json"}
            with patch.object(test_sport.server, "ROOT", app):
                fixture = test_sport.Sport()
                for filename in ("index.html", "assistant.html"):
                    page = PageAssets()
                    page.feed((app / "web" / filename).read_text(encoding="utf8"))
                    for asset in page.assets:
                        self.assertIn("web/" + virtual.get(asset, asset), image_sources)
                        status, content = fixture.call("/" + asset)
                        self.assertEqual(status, 200, asset)
                        self.assertTrue(content, asset)
            self.assertIn((app / "web" / "health.css").read_text(encoding="utf8"), preview)
            subprocess.run([sys.executable, "-B", "-c", "import server, health_sensors"],
                           cwd=app, env={**os.environ, "SPORT_DATA": str(folder / "empty-data")}, check=True)
            zip_bytes = (folder / "Sport-HA.zip").read_bytes()
            package.build(folder)
            self.assertEqual((folder / "Sport-HA.zip").read_bytes(), zip_bytes)
